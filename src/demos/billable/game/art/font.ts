/** Normalise any string to characters the font can draw. */
export function fontSafe(text: string): string {
  return [
    ...text
      .replace(/[\u2018\u2019]/g, "'")
      .replace(/[\u201c\u201d]/g, '"')
      .replace(/\u2014/g, '-'),
  ]
    .map((c) => (c === '\n' || FONT_CHARS.includes(c) ? c : '?'))
    .join('');
}
